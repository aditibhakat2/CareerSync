import { verifyToken } from '../config/jwt.js';

export const authenticateJWT = (req, res, next) => {
  const authHeader = req.headers.authorization;
  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ success: false, message: 'Access denied. No token provided.' });
  }

  const token = authHeader.split(' ')[1];
  try {
    const decoded = verifyToken(token);
    req.user = decoded;
    next();
  } catch (error) {
    return res.status(403).json({ success: false, message: 'Invalid or expired token.' });
  }
};

export const authorizeRole = (...allowedRoles) => {
  return (req, res, next) => {
    if (!req.user || !allowedRoles.includes(req.user.role)) {
      return res.status(403).json({ success: false, message: `Forbidden. Access reserved for ${allowedRoles.join(', ')} roles.` });
    }
    next();
  };
};

export const authorizeStudent = authorizeRole('Student');
export const authorizeCompany = authorizeRole('Company');
export const authorizeAdmin = authorizeRole('Admin');
